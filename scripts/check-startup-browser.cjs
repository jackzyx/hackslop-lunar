const { chromium } = require('../.slide-tools/node_modules/playwright');
const assert = require('node:assert/strict');
const base = process.env.TEST_URL || 'http://127.0.0.1:5174/';
(async () => {
 const browser=await chromium.launch({executablePath:process.env.CHROME_PATH||(process.platform==='win32'?'C:/Program Files/Google/Chrome/Application/chrome.exe':undefined),headless:true});
 try {
  const bare=await browser.newPage({viewport:{width:1440,height:900}});
  await bare.route(/\/(src\/main\.jsx|assets\/index-[^/]+\.js)/,route=>route.abort());
  await bare.goto(base,{waitUntil:'domcontentloaded'});
  const colors=await bare.evaluate(()=>({html:getComputedStyle(document.documentElement).backgroundColor,body:getComputedStyle(document.body).backgroundColor,intro:getComputedStyle(document.querySelector('#intro')).backgroundColor}));
  assert.equal(colors.html,'rgb(5, 4, 3)');assert.equal(colors.body,'rgb(5, 4, 3)');assert.equal(colors.intro,'rgb(0, 0, 0)');
  assert.ok(await bare.locator('#intro-boot').isVisible());
  await bare.screenshot({path:'.slide-tools/first-paint-dark.png'});
  await bare.keyboard.press('x');
  assert.equal(await bare.locator('#intro').getAttribute('data-initialised'),'true');
  assert.equal(await bare.locator('#intro').isVisible(),true);
  await bare.getByRole('button',{name:'Skip intro'}).click();
  assert.equal(await bare.locator('#intro').isVisible(),false);
  const page=await browser.newPage({viewport:{width:1440,height:900}}),errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.route('**/terrain_500m.bin',async route=>{await new Promise(r=>setTimeout(r,1800));await route.continue()});
  const start=Date.now();await page.goto(base,{waitUntil:'domcontentloaded'});
  await page.getByRole('button',{name:'[PRESS ANY KEY TO INITIALISE]',exact:true}).waitFor();
  await page.waitForFunction(()=>document.querySelector('#intro').dataset.phase==='waiting');
  await page.waitForFunction(()=>document.querySelector('#intro').dataset.assets==='complete');
  await page.waitForFunction(()=>document.querySelector('#intro').dataset.earth==='nasa-blue-marble');
  await page.evaluate(()=>{window.waitingCanvas=document.querySelector('.intro-scene canvas');window.waitingPixels=window.waitingCanvas.toDataURL()});
  await page.waitForTimeout(700);
  assert.equal(await page.locator('#intro').getAttribute('data-phase'),'waiting','intro started without input');
  assert.equal(await page.locator('#intro').getAttribute('data-time'),'0.000');
  assert.ok(await page.evaluate(()=>window.waitingCanvas.toDataURL()===window.waitingPixels),'first-frame pixels changed while waiting');
  await page.screenshot({path:'.slide-tools/intro-first-frame-waiting.png'});
  await page.keyboard.press('Enter');
  await page.waitForFunction(()=>document.querySelector('#intro').dataset.phase==='playing'&&Number(document.querySelector('#intro').dataset.time)>.1);
  const motionMs=Date.now()-start;
  assert.ok(await page.evaluate(()=>window.waitingCanvas===document.querySelector('.intro-scene canvas')),'start replaced the waiting canvas');
  await page.waitForFunction(()=>document.querySelector('#intro').hidden,{timeout:30000});
  await page.getByRole('navigation',{name:'Footer navigation'}).waitFor();
  assert.deepEqual(errors,[]);
  console.log(JSON.stringify({firstPaint:colors,firstFrameHeld:'passed',sameCanvasOnStart:'passed',earlyInitialisation:'passed',skipBeforeJS:'passed',motionMs,plannerReveal:'passed',pageErrors:errors}));
 }finally{await browser.close()}
})().catch(e=>{console.error(e);process.exitCode=1});
